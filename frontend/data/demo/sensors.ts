// Generate time-series readings for a sensor (last 24 hours)
export function generateSensorHistory(
  sensorId: string,
  baseValue: number,
  variance: number,
  points: number = 24
): SensorReading[] {
  const readings: SensorReading[] = [];
  const now = Date.now();
  for (let i = points; i >= 0; i--) {
    const timestamp = new Date(now - i * 60 * 60 * 1000).toISOString();
    const jitter = (Math.random() - 0.5) * variance * 2;
    const value = Math.max(0, baseValue + jitter + (points - i) * (variance / points) * 0.3);
    readings.push({
      id: `reading-${sensorId}-${i}`,
      sensorId,
      value: parseFloat(value.toFixed(1)),
      timestamp,
      status: "NORMAL",
    });
  }
  return readings;
}
